#!/usr/bin/env python3
"""Synthetic Android-emulator checks; never reads real user input or publishes an APK."""
from __future__ import annotations

import argparse
import base64
import gzip
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "dev.jason.com.google.android.inputmethod.latin"
PROBE_PACKAGE = "dev.arena.gboardprobe"
PROBE_ACTIVITY = "dev.jason.gboardpatches.extension.directtranslate.AndroidSyntheticActivity"
INSPECTOR_PACKAGE = "dev.arena.gboardinspector"
INSPECTOR_RUNNER = "dev.jason.gboardpatches.extension.directtranslate.AndroidWindowInspector"


def run(*command: str, timeout: int = 60) -> str:
    result = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            timeout=timeout, check=False)
    if result.returncode:
        # Surface only a stage and a constrained error code/type; never publish
        # response bodies, emulator logcat, or arbitrary command output.
        program = Path(command[0]).name
        stage = program
        if program == "adb":
            stage += " " + ("app_process" if "app_process" in command else command[1])
        code = re.search(r"\bINSTALL_FAILED_[A-Z0-9_]+\b", result.stdout)
        exception = re.search(r"\b(?:[a-zA-Z_][\w$]*\.)*[a-zA-Z_][\w$]*(?:Exception|Error)\b", result.stdout)
        compile_error = re.search(r"error: ([A-Za-z0-9_ .-]{1,100})", result.stdout) if program in ("javac", "d8") else None
        # aapt only sees manifests generated by this disposable synthetic test;
        # keep a constrained diagnostic but never include paths or raw output.
        aapt_error = re.search(r"(?:ERROR|error):\s*([A-Za-z0-9_ .,:-]{1,120})", result.stdout) if program == "aapt" else None
        detail = (code.group(0) if code else exception.group(0) if exception else
                  compile_error.group(1) if compile_error else aapt_error.group(1).strip() if aapt_error else None)
        suffix = f" [{detail}]" if detail else ""
        raise RuntimeError(f"{stage} failed (exit {result.returncode}){suffix}")
    return result.stdout.strip()


def dump_ui() -> str:
    run("adb", "shell", "uiautomator", "dump", "/sdcard/gboard-smoke-window.xml", timeout=45)
    return run("adb", "exec-out", "cat", "/sdcard/gboard-smoke-window.xml", timeout=20)


def publish_synthetic_ui(xml: str, label: str) -> None:
    # Fresh emulator, no account or user input. Compress annotations in small
    # chunks for temporary debugging; no APKs or full logcat are uploaded.
    packed = base64.b64encode(gzip.compress(xml.encode("utf-8"))).decode("ascii")
    chunks = [packed[i:i + 2800] for i in range(0, len(packed), 2800)]
    if len(chunks) > 15:
        print(f"::notice::{label}: synthetic UI tree too large to annotate")
        return
    for index, chunk in enumerate(chunks, 1):
        print(f"::notice::{label} {index}/{len(chunks)} {chunk}")


def center(bounds: str) -> tuple[int, int] | None:
    match = re.fullmatch(r"\[(\d+),(\d+)\]\[(\d+),(\d+)\]", bounds or "")
    if not match:
        return None
    x1, y1, x2, y2 = map(int, match.groups())
    return ((x1 + x2) // 2, (y1 + y2) // 2) if x2 > x1 and y2 > y1 else None


def tap_search(xml: str) -> bool:
    nodes = list(ET.fromstring(xml).iter("node"))
    for node in nodes:
        description = (node.get("content-desc", "") + " " + node.get("text", "")).lower()
        identifier = node.get("resource-id", "").lower()
        if "search" not in description and "search" not in identifier:
            continue
        position = center(node.get("bounds", ""))
        if position:
            run("adb", "shell", "input", "tap", str(position[0]), str(position[1]))
            return True
    return False


def ime_visibility_flags(dump: str) -> dict[str, bool]:
    """Keep only known boolean flags; never save arbitrary dumpsys output."""
    names = ("mInputShown", "isInputViewShown", "mShowRequested", "mShowExplicitlyRequested",
             "mShowForced", "mInputViewStarted")
    return {name: value == "true" for name, value in re.findall(
        r"\b(" + "|".join(names) + r")\s*=\s*(true|false)\b", dump)}


def tap_synthetic_editor(xml: str) -> bool:
    for node in ET.fromstring(xml).iter("node"):
        if node.get("package") != PROBE_PACKAGE or node.get("class") != "android.widget.EditText":
            continue
        position = center(node.get("bounds", ""))
        if position:
            run("adb", "shell", "input", "tap", str(position[0]), str(position[1]))
            return True
    return False


def gboard_crash_types(log: str) -> list[str]:
    """Return exception class names for Gboard fatal crashes, not their messages."""
    crashes = []
    for section in re.split(r"(?=FATAL EXCEPTION:)", log):
        if "FATAL EXCEPTION:" not in section or not re.search(
                r"\bProcess:\s*" + re.escape(PACKAGE) + r"(?:\s|,|$)", section):
            continue
        crashes.extend(re.findall(
            r"\b(?:[a-zA-Z_$][\w$]*\.)*[a-zA-Z_$][\w$]*(?:Exception|Error)\b(?=:|\s|$)", section))
    return sorted(set(crashes))


def synthetic_http_probe() -> None:
    sdk = Path(os.environ["ANDROID_HOME"])
    android_jar = sdk / "platforms/android-35/android.jar"
    candidates = [p for p in (sdk / "build-tools").iterdir() if (p / "d8").is_file()]
    tools = max(candidates, key=lambda p: tuple(int(n) for n in re.findall(r"\d+", p.name)), default=None)
    if not android_jar.is_file() or tools is None:
        raise RuntimeError("Required Android SDK platform or build tools not found")
    with tempfile.TemporaryDirectory(prefix="gboard-android-probe-") as directory:
        tmp = Path(directory)
        classes, dex = tmp / "classes", tmp / "dex"
        classes.mkdir()
        dex.mkdir()
        source = ROOT / "tools/gboard-translate/overlay/extensions/extension/src/main/java/dev/jason/gboardpatches/extension/directtranslate"
        run("javac", "-source", "8", "-target", "8", "-encoding", "UTF-8", "-cp", str(android_jar),
            "-d", str(classes), str(source / "GtxClient.java"), str(source / "TranslateCoordinator.java"),
            str(ROOT / "tools/gboard-translate/AndroidSyntheticActivity.java"),
            str(ROOT / "tools/gboard-translate/AndroidWindowInspector.java"), timeout=90)
        class_files = sorted(map(str, classes.rglob("*.class")))
        if not class_files:
            raise RuntimeError("Probe compilation generated no classes")
        run(str(tools / "d8"), "--min-api", "26", "--lib", str(android_jar), "--output", str(dex),
            *class_files, timeout=90)
        manifest = tmp / "AndroidManifest.xml"
        manifest.write_text('''<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="dev.arena.gboardprobe">
  <uses-sdk android:minSdkVersion="26" android:targetSdkVersion="32" />
  <uses-permission android:name="android.permission.INTERNET" />
  <application android:label="Gboard synthetic test">
    <activity android:name="dev.jason.gboardpatches.extension.directtranslate.AndroidSyntheticActivity" android:exported="true" />
  </application>
</manifest>''', encoding="utf-8")
        unsigned, aligned, signed, key = tmp / "unsigned.apk", tmp / "aligned.apk", tmp / "probe.apk", tmp / "test.keystore"
        run(str(tools / "aapt"), "package", "-f", "-M", str(manifest), "-I", str(android_jar), "-F", str(unsigned))
        with zipfile.ZipFile(unsigned, "a") as archive:
            archive.write(dex / "classes.dex", "classes.dex")
        run(str(tools / "zipalign"), "-f", "4", str(unsigned), str(aligned))
        # Ephemeral local debug keystore; it is not a user credential.
        run("keytool", "-genkeypair", "-noprompt", "-keystore", str(key), "-storepass", "android",
            "-keypass", "android", "-alias", "test", "-dname", "CN=Gboard emulator test", "-keyalg", "RSA",
            "-keysize", "2048", "-validity", "2", timeout=45)
        run(str(tools / "apksigner"), "sign", "--ks", str(key), "--ks-pass", "pass:android",
            "--key-pass", "pass:android", "--out", str(signed), str(aligned), timeout=45)
        run("adb", "install", "-r", str(signed), timeout=90)
        try:
            # A separate no-activity package lets UiAutomation enumerate the IME
            # window without restarting the focused synthetic editor app.
            inspector_dir = tmp / "inspector"
            inspector_dir.mkdir()
            inspector_manifest = inspector_dir / "AndroidManifest.xml"
            inspector_manifest.write_text('''<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="dev.arena.gboardinspector">
  <uses-sdk android:minSdkVersion="26" android:targetSdkVersion="32" />
  <application android:label="Gboard synthetic window inspector" />
  <instrumentation android:name="dev.jason.gboardpatches.extension.directtranslate.AndroidWindowInspector"
      android:targetPackage="dev.arena.gboardinspector" />
</manifest>''', encoding="utf-8")
            inspector_unsigned, inspector_aligned, inspector_signed = (
                tmp / "inspector-unsigned.apk", tmp / "inspector-aligned.apk", tmp / "inspector.apk")
            run(str(tools / "aapt"), "package", "-f", "-M", str(inspector_manifest), "-I", str(android_jar),
                "-F", str(inspector_unsigned))
            with zipfile.ZipFile(inspector_unsigned, "a") as archive:
                archive.write(dex / "classes.dex", "classes.dex")
            run(str(tools / "zipalign"), "-f", "4", str(inspector_unsigned), str(inspector_aligned))
            run(str(tools / "apksigner"), "sign", "--ks", str(key), "--ks-pass", "pass:android",
                "--key-pass", "pass:android", "--out", str(inspector_signed), str(inspector_aligned), timeout=45)
            run("adb", "install", "-r", str(inspector_signed), timeout=90)
        except (RuntimeError, OSError, subprocess.TimeoutExpired) as error:
            # Inspector setup must not mask the independent HTTPS result.
            print(f"::warning::IME inspector setup failed: {type(error).__name__}: {error}")
        run("adb", "logcat", "-c")
        run("adb", "shell", "am", "start", "-n", f"{PROBE_PACKAGE}/{PROBE_ACTIVITY}")
        expected = {"PASS_EN_KM", "PASS_KM_EN", "PASS_AUTO_KM"}
        deadline = time.monotonic() + 75
        while time.monotonic() < deadline:
            lines = run("adb", "logcat", "-d", "-s", "GboardDirectSmoke:I", "*:S", timeout=15)
            markers = set(re.findall(r"\b(?:PASS|FAIL)_(?:EN_KM|KM_EN|AUTO_KM)(?:_[A-Za-z]+)?\b", lines))
            if markers == expected:
                print("::notice::Android emulator app passed synthetic HTTPS POST in both directions and auto mode.")
                return
            if any(item.startswith("FAIL_") for item in markers):
                raise RuntimeError("Android synthetic HTTPS probe returned " + ",".join(sorted(markers)))
            time.sleep(3)
        raise RuntimeError("Android synthetic HTTPS probe did not finish")


def inspect_ime_windows() -> list:
    result = run("adb", "shell", "am", "instrument", "-w", "-r",
                 f"{INSPECTOR_PACKAGE}/{INSPECTOR_RUNNER}", timeout=45)
    match = re.search(r"^INSTRUMENTATION_RESULT: ime_windows=([A-Za-z0-9+/=]+)$", result, re.MULTILINE)
    if not match:
        error = re.search(r"^INSTRUMENTATION_RESULT: error=([A-Za-z0-9_]+)$", result, re.MULTILINE)
        raise RuntimeError("IME window inspector did not return a tree" + (f" [{error.group(1)}]" if error else ""))
    data = json.loads(gzip.decompress(base64.b64decode(match.group(1))).decode("utf-8"))
    if not isinstance(data, list):
        raise RuntimeError("IME window inspector returned an invalid tree")
    return data


def flatten_window_nodes(windows: list):
    for window in windows:
        if not isinstance(window, dict):
            continue
        yield window
        yield from flatten_window_nodes(window.get("children", []))


def tap_ime_label(windows: list, label: str) -> bool:
    for node in flatten_window_nodes(windows):
        description = (str(node.get("description", "")) + " " + str(node.get("text", ""))).lower()
        if label.lower() not in description:
            continue
        position = center(node.get("bounds", ""))
        if position:
            run("adb", "shell", "input", "tap", str(position[0]), str(position[1]))
            return True
    return False


def gboard_ime_smoke(apk: Path, report: dict) -> None:
    run("adb", "install", "-r", str(apk), timeout=180)
    report["fixture_install"] = "passed"
    # Package manager can report install success before the input-method
    # service registry reflects the new package on a cold emulator.
    deadline = time.monotonic() + 25
    candidates = []
    while time.monotonic() < deadline:
        methods = run("adb", "shell", "ime", "list", "-s", "-a")
        candidates = [line.strip() for line in methods.splitlines() if line.strip().startswith(PACKAGE + "/")]
        if len(candidates) >= 1:
            break
        time.sleep(2)
    report["ime_components_found"] = len(candidates)
    if len(candidates) != 1:
        raise RuntimeError("Expected one Gboard IME component in the emulator")
    ime = candidates[0]
    run("adb", "shell", "ime", "enable", ime)
    run("adb", "shell", "ime", "set", ime)
    run("adb", "shell", "settings", "put", "secure", "show_ime_with_hard_keyboard", "1")
    if run("adb", "shell", "settings", "get", "secure", "default_input_method") != ime:
        raise RuntimeError("Gboard was not selected as the emulator IME")
    report["ime_enable_and_select"] = "passed"
    # The first ARM-translated start can be slow. Explicitly tap the fresh
    # synthetic editor and allow time for IME initialization before recording
    # a negative result; do not assume that a running process means visible UI.
    run("adb", "logcat", "-c")
    run("adb", "shell", "am", "start", "-S", "-n", f"{PROBE_PACKAGE}/{PROBE_ACTIVITY}")
    time.sleep(6)
    tap_synthetic_editor(dump_ui())
    deadline = time.monotonic() + 35
    flags = {}
    while time.monotonic() < deadline:
        dump = run("adb", "shell", "dumpsys", "input_method", timeout=30)
        flags = ime_visibility_flags(dump)
        if flags.get("mInputShown") or flags.get("isInputViewShown"):
            break
        time.sleep(5)
    report["ime_visibility_flags"] = flags
    visible = flags.get("mInputShown", False) or flags.get("isInputViewShown", False)
    report["keyboard_visibility_signal"] = "passed" if visible else "not confirmed"
    crashes = gboard_crash_types(run("adb", "logcat", "-d", "-s", "AndroidRuntime:E", "*:S", timeout=30))
    if crashes:
        report["gboard_fatal_exception_types"] = crashes
    pid = run("adb", "shell", "pidof", PACKAGE)
    if not re.fullmatch(r"[0-9 ]+", pid):
        raise RuntimeError("Gboard process did not start")
    report["ime_process_started"] = "passed"
    ui = dump_ui()
    publish_synthetic_ui(ui, "GBOARD_KEYBOARD_UI")
    # uiautomator dump may return only the foreground app, not the separate
    # keyboard window. The disposable instrumentation enumerates IME windows.
    try:
        windows = inspect_ime_windows()
        report["ime_accessibility_windows"] = len(windows)
        publish_synthetic_ui(json.dumps(windows, ensure_ascii=False), "GBOARD_IME_WINDOWS")
        # Translate can be tucked into the features menu instead of the
        # initial toolbar. Tap only known accessibility labels in this fresh
        # emulator; tapping is not evidence that translation itself succeeded.
        if not any("translate" in (str(n.get("description", "")) + " " + str(n.get("text", ""))).lower()
                   for n in flatten_window_nodes(windows)):
            if tap_ime_label(windows, "open features menu"):
                report["features_menu_tapped"] = True
                time.sleep(3)
                windows = inspect_ime_windows()
                publish_synthetic_ui(json.dumps(windows, ensure_ascii=False), "GBOARD_FEATURE_MENU")
        if tap_ime_label(windows, "translate"):
            time.sleep(3)
            publish_synthetic_ui(json.dumps(inspect_ime_windows(), ensure_ascii=False), "GBOARD_TRANSLATE_UI")
            report["translate_button_tapped"] = "attempted; translation not yet asserted"
    except (RuntimeError, ValueError, OSError, subprocess.TimeoutExpired) as error:
        report["ime_inspector_error"] = type(error).__name__
        print(f"::warning::IME accessibility inspector could not complete: {type(error).__name__}")
    print("::notice::Third-party-derived Gboard fixture installed and its IME process started in an emulator.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fixture_apk", type=Path)
    parser.add_argument("report", type=Path)
    args = parser.parse_args()
    report = {
        "environment": "Android emulator only, not the user's device or network",
        "apk": "test hybrid: third-party prepatched resources/renamed manifest plus Morphe-patched DEX; re-signed, not stock",
        "synthetic_android_java_https": "not run", "fixture_install": "not run",
        "ime_enable_and_select": "not run", "ime_process_started": "not run",
        "keyboard_visibility_signal": "not run", "translate_ui_functionality": "not tested",
        "translate_button_tapped": "not located",
    }
    failed = False
    try:
        report["android_api"] = run("adb", "shell", "getprop", "ro.build.version.sdk")
        report["android_abi_list"] = run("adb", "shell", "getprop", "ro.product.cpu.abilist")
        try:
            synthetic_http_probe()
            report["synthetic_android_java_https"] = "passed"
        except (RuntimeError, subprocess.TimeoutExpired, OSError) as error:
            report["synthetic_android_java_https"] = "failed or unavailable"
            report["synthetic_error"] = str(error)
            print(f"::warning::Android synthetic client probe failed: {type(error).__name__}: {error}")
            failed = True
        try:
            gboard_ime_smoke(args.fixture_apk, report)
        except (RuntimeError, subprocess.TimeoutExpired, OSError, ET.ParseError) as error:
            report["ime_smoke_error"] = str(error)
            print(f"::warning::Android fixture IME smoke could not complete: {type(error).__name__}: {error}")
            failed = True
    finally:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
